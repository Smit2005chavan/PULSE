def to_yf(symbol: str) -> str:
    """NSE symbol -> yfinance ticker."""
    return f"{symbol}.NS"


def get_symbol(company_name: str):
    """Return (nse_symbol, confidence) for a broker company name, or (None, None)."""
    entry = TICKER_MAP.get(company_name.strip())
    if entry:
        return entry
    return None, None
